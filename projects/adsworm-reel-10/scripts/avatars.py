"""Turn generated character sheets (3 poses on flat green) into per-pose transparent PNGs.

    python3 scripts/avatars.py aman=/path/aman-sheet.png:idle,point,thumbs founder=/path/founder-sheet.png:idle,think,wow

Writes public/avatars/<who>-<pose>.png (all poses of one character share a canvas, feet aligned
to the bottom so scale stays consistent) and src/reel/avatars.ts (the pose manifest).
"""
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "public/avatars"


def key_green(im: Image.Image) -> Image.Image:
    a = np.asarray(im.convert("RGB")).astype(np.int16)
    r, g, b = a[..., 0], a[..., 1], a[..., 2]
    bg = (g > 90) & (g > r * 1.35) & (g > b * 1.35)  # bright key + the darker shadow ellipse
    alpha = np.where(bg, 0, 255).astype(np.uint8)
    # soften the cut edge by one pixel
    soft = np.asarray(Image.fromarray(alpha).filter(ImageFilter.GaussianBlur(1)))
    alpha = np.minimum(alpha, soft).astype(np.uint8)
    # despill: green fringe on edge pixels → neutral
    spill = (~bg) & (g > np.maximum(r, b) + 12)
    g2 = np.where(spill, np.maximum(r, b), g)
    rgb = np.stack([r, g2, b], axis=-1).clip(0, 255).astype(np.uint8)
    return Image.fromarray(np.dstack([rgb, alpha]), "RGBA")


def split(im: Image.Image, n: int):
    alpha = np.asarray(im)[..., 3]
    cols = (alpha > 8).any(axis=0)
    runs, start = [], None
    for x, on in enumerate(list(cols) + [False]):
        if on and start is None:
            start = x
        if not on and start is not None:
            runs.append([start, x])
            start = None
    # merge runs separated by small gaps (a raised hand can detach from the body column-wise)
    merged = [runs[0]]
    for a, b in runs[1:]:
        if a - merged[-1][1] < 40:
            merged[-1][1] = b
        else:
            merged.append([a, b])
    merged = sorted(merged, key=lambda r: r[1] - r[0], reverse=True)[:n]
    merged.sort()
    crops = []
    for a, b in merged:
        sub = im.crop((max(0, a - 6), 0, min(im.width, b + 6), im.height))
        bbox = sub.getbbox()
        crops.append(sub.crop(bbox))
    return crops


def main(args):
    OUT.mkdir(parents=True, exist_ok=True)
    manifest = {}
    for spec in args:
        who, rest = spec.split("=", 1)
        path, poses = rest.split(":", 1)
        poses = poses.split(",")
        im = key_green(Image.open(path))
        crops = split(im, len(poses))
        H = max(c.height for c in crops)
        W = max(c.width for c in crops)
        manifest[who] = {}
        for pose, c in zip(poses, crops):
            canvas = Image.new("RGBA", (W, H), (0, 0, 0, 0))
            canvas.paste(c, ((W - c.width) // 2, H - c.height), c)  # feet on the floor
            name = f"{who}-{pose}.png"
            canvas.save(OUT / name, optimize=True)
            manifest[who][pose] = f"avatars/{name}"
            print(f"{name}: {c.width}×{c.height} on {W}×{H}")
    ts = "// Generated by scripts/avatars.py — pose files available per character (public/avatars/*.png).\nexport const AVATARS: Record<string, Partial<Record<string, string>>> = " + __import__("json").dumps(manifest, indent=2) + ";\n"
    (ROOT / "src/reel/avatars.ts").write_text(ts)
    print("→ src/reel/avatars.ts")


if __name__ == "__main__":
    main(sys.argv[1:])
